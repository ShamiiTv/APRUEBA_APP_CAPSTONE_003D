// Browser fixtures only; this script never edits a real profile.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const { chromium }=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({ headless:true,executablePath:process.env.CHROME_EXECUTABLE || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
try {
  const context=await browser.newContext({ viewport:{ width:1280,height:900 } });
  await context.addInitScript(() => {
    if (!localStorage.getItem('token')) localStorage.setItem('token','browser-fixture');
    if (!localStorage.getItem('theme')) localStorage.setItem('theme','light');
    if (!localStorage.getItem('lang')) localStorage.setItem('lang','es');
  });
  const page=await context.newPage(); const errors=[];
  page.on('pageerror',error => errors.push(error.message));
  let user={ uid:'fixture',name:'Alumna inicial',email:'fixture@example.test',onboardingCompleted:true,school:'Colegio inicial',region:'Biobío',selectedTests:['m1'],difficulty:'d2',theme:'dark',locale:'en',dailyReminder:false,medals:{ bronze:17 },quota:{ used:0,max:20 },streak:0 };
  let failSave=false,holdSave=null;
  const writes=[]; const practiceRequests=[];
  await page.route('http://localhost:4000/api/v1/**',async route => {
    const request=route.request(); const url=new URL(request.url()); const path=url.pathname;
    const headers={ 'access-control-allow-origin':'*','access-control-allow-headers':'*','access-control-allow-methods':'GET,PATCH,POST,OPTIONS' };
    if (request.method()==='OPTIONS') return route.fulfill({ status:204,headers });
    if (path.endsWith('/auth/profile') && request.method()==='PATCH') {
      const patch=request.postDataJSON(); writes.push(patch);
      if (holdSave) await holdSave;
      if (failSave) return route.fulfill({ status:503,headers,json:{ data:null,error:{ message:'No se pudo guardar el perfil.',code:'PROFILE_UNAVAILABLE' } } });
      user={ ...user,...patch,name:(patch.name ?? user.name).trim() };
      return route.fulfill({ headers,json:{ data:user,error:null } });
    }
    if (path.endsWith('/auth/me')) return route.fulfill({ headers,json:{ data:user,error:null } });
    if (path.endsWith('/practice/next')) practiceRequests.push(url.searchParams);
    return route.fulfill({ headers,json:{ data:{ question:null,noQuestions:true,allCompleted:false,user },error:null,meta:{} } });
  });
  const url=(process.env.WEB_TEST_URL || 'http://127.0.0.1:5173')+'/ajustes';
  await page.goto(url);
  await page.getByRole('heading',{ name:'Profile and settings' }).waitFor();
  const form=page.locator('.settings-page');
  assert.equal(await page.evaluate(() => document.body.classList.contains('dark')),true);
  assert.equal(await form.getByLabel('Name',{exact:true}).inputValue(),'Alumna inicial');
  assert.equal(await form.getByLabel('Account email',{exact:true}).getAttribute('readonly'),'');
  console.log('PASS: saved account appearance overrides local browser preferences');
  await form.getByLabel('Name',{exact:true}).fill('  Nombre actualizado  ');
  await form.getByLabel('School or institution (optional)',{exact:true}).fill('Colegio nuevo');
  await form.getByLabel('Region (optional)',{exact:true}).fill('');
  await form.getByRole('checkbox',{ name:'Matemática M1',exact:true }).uncheck();
  await form.getByRole('checkbox',{ name:'Matemática M2',exact:true }).check();
  await form.getByLabel('Preferred difficulty',{exact:true}).selectOption('d3');
  await form.getByLabel('Theme',{exact:true}).selectOption('light');
  await form.getByLabel('Interface language',{exact:true}).selectOption('es');
  await form.getByRole('checkbox',{ name:'Daily reminder preference',exact:true }).check();
  await form.getByRole('button',{ name:'Save changes',exact:true }).click();
  await page.getByText('Tu perfil y preferencias quedaron guardados.').waitFor();
  assert.equal(writes.length,1); assert.equal(user.medals.bronze,17);
  assert.equal(await page.evaluate(() => document.body.classList.contains('dark')),false);
  await page.reload();
  await page.getByRole('heading',{ name:'Perfil y ajustes' }).waitFor();
  assert.equal(await form.getByLabel('Nombre',{exact:true}).inputValue(),'Nombre actualizado');
  assert.equal(await form.getByLabel('Región (opcional)',{exact:true}).inputValue(),'');
  assert.equal(await form.getByLabel('Dificultad preferida',{exact:true}).inputValue(),'d3');
  console.log('PASS: profile, cleared optional fields and typed preferences persist after reload');
  await page.getByRole('link',{ name:'Practicar',exact:true }).click();
  await page.waitForURL('**/practicar');
  await page.waitForResponse(response => response.url().includes('/practice/next'));
  assert.equal(practiceRequests.at(-1).get('testId'),'m2'); assert.equal(practiceRequests.at(-1).get('difficulty'),'d3');
  console.log('PASS: generic practice uses saved subject and difficulty');
  await page.goto(url); await page.getByRole('heading',{ name:'Perfil y ajustes' }).waitFor();
  failSave=true;
  await form.getByLabel('Nombre',{exact:true}).fill('Cambio pendiente');
  await form.getByLabel('Tema',{exact:true}).selectOption('dark');
  await form.getByRole('button',{ name:'Guardar cambios',exact:true }).click();
  await page.getByRole('alert').waitFor();
  assert.equal(await form.getByLabel('Nombre',{exact:true}).inputValue(),'Cambio pendiente');
  assert.equal(user.name,'Nombre actualizado');
  assert.equal(await page.evaluate(() => document.body.classList.contains('dark')),false);
  failSave=false;
  await form.getByRole('button',{ name:'Guardar cambios',exact:true }).click();
  await page.getByText('Tu perfil y preferencias quedaron guardados.').waitFor();
  assert.equal(user.name,'Cambio pendiente');
  assert.equal(await page.evaluate(() => document.body.classList.contains('dark')),true);
  console.log('PASS: failed save preserves the draft and applies appearance only after a successful retry');
  await form.getByLabel('Nombre',{exact:true}).fill('Borrador descartado');
  const writeCount=writes.length;
  await form.getByRole('button',{ name:'Descartar cambios',exact:true }).click();
  assert.equal(await form.getByLabel('Nombre',{exact:true}).inputValue(),'Cambio pendiente');
  assert.equal(writes.length,writeCount);
  console.log('PASS: discarding changes restores the current profile without writing');
  await form.getByLabel('Nombre',{exact:true}).fill('Nombre final');
  await page.locator('select[aria-label="Idioma de la interfaz"]').selectOption('en');
  await page.getByRole('heading',{ name:'Profile and settings' }).waitFor();
  assert.equal(await form.getByLabel('Interface language',{exact:true}).inputValue(),'en');
  assert.equal(await form.getByLabel('Name',{exact:true}).inputValue(),'Nombre final');
  await form.getByRole('button',{ name:'Save changes',exact:true }).click();
  await page.getByText('Your profile and preferences were saved.').waitFor();
  assert.deepEqual(writes.at(-1),{ name:'Nombre final' });
  assert.equal(user.locale,'en');
  console.log('PASS: menu preferences persist without being overwritten by an unrelated profile edit');
  let releaseSave; holdSave=new Promise(resolve => { releaseSave=resolve; });
  await form.getByLabel('Name',{exact:true}).fill('Pending logout edit');
  const pendingResponse=page.waitForResponse(response => response.url().endsWith('/auth/profile') && response.request().method()==='PATCH');
  await form.getByRole('button',{ name:'Save changes',exact:true }).click();
  await page.locator('aside button').last().click();
  await page.waitForURL('**/login');
  releaseSave(); await pendingResponse; await page.waitForTimeout(100);
  assert.equal(new URL(page.url()).pathname,'/login');
  assert.equal(await page.evaluate(() => localStorage.getItem('token')),null);
  console.log('PASS: a late profile response cannot restore a logged-out session');
  holdSave=null;
  user={ uid:'second-fixture',name:'Segunda cuenta',email:'second@example.test',onboardingCompleted:true,selectedTests:['m1'] };
  await page.evaluate(() => localStorage.setItem('token','second-browser-fixture'));
  await page.goto(url); await page.getByRole('heading',{ name:'Perfil y ajustes' }).waitFor();
  assert.equal(await form.getByLabel('Nombre',{exact:true}).inputValue(),'Segunda cuenta');
  assert.equal(await page.evaluate(() => document.body.classList.contains('dark')),false);
  assert.equal(await page.evaluate(() => document.documentElement.lang),'es');
  assert.deepEqual(errors,[]);
  console.log('PASS: another account receives its own defaults rather than the previous account settings');
} finally { await browser.close(); }
